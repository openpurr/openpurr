// Generates the suite's TEST-ONLY keys and certificates into fixtures/generated.json (git-ignored).
// Nothing here is trusted by any real system. `--if-missing` keeps an existing set; run
// `pnpm --filter @openpurr/conformance fixtures` for a fresh one (then restart the server under
// test, which trusts the root and holds the store keys).
//
// The Apple chain has the shape of an App Store signed transaction's:
//   root (P-384, self-signed) -> intermediate (P-384, Apple's WWDR marker) -> leaf (P-256, Apple's
//   receipt-signing marker), JWS alg ES256 with an x5c header.

import { webcrypto as crypto, randomBytes } from "node:crypto";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import "reflect-metadata";
import * as x509 from "@peculiar/x509";
import { exportPKCS8 } from "jose";

const target = fileURLToPath(new URL("../fixtures/generated.json", import.meta.url));
if (process.argv.includes("--if-missing") && existsSync(target)) process.exit(0);

x509.cryptoProvider.set(crypto);

const P384 = { name: "ECDSA", namedCurve: "P-384" };
const P256 = { name: "ECDSA", namedCurve: "P-256" };
const SHA384 = { name: "ECDSA", hash: "SHA-384" };
const RSA = { name: "RSASSA-PKCS1-v1_5", modulusLength: 2048, publicExponent: new Uint8Array([1, 0, 1]), hash: "SHA-256" };
const notBefore = new Date("2026-01-01T00:00:00Z");
const notAfter = new Date("2036-01-01T00:00:00Z");
const b64 = (cert) => Buffer.from(cert.rawData).toString("base64");

const rootKeys = await crypto.subtle.generateKey(P384, true, ["sign", "verify"]);
const root = await x509.X509CertificateGenerator.createSelfSigned({
  serialNumber: "01",
  name: "CN=openpurr CONFORMANCE Root CA, O=openpurr test fixtures",
  notBefore,
  notAfter,
  keys: rootKeys,
  signingAlgorithm: SHA384,
  extensions: [new x509.BasicConstraintsExtension(true, undefined, true)],
});

const intKeys = await crypto.subtle.generateKey(P384, true, ["sign", "verify"]);
const intermediate = await x509.X509CertificateGenerator.create({
  serialNumber: "02",
  subject: "CN=openpurr CONFORMANCE Intermediate CA, O=openpurr test fixtures",
  issuer: root.subject,
  notBefore,
  notAfter,
  publicKey: intKeys.publicKey,
  signingKey: rootKeys.privateKey,
  signingAlgorithm: SHA384,
  extensions: [
    new x509.BasicConstraintsExtension(true, 0, true),
    new x509.Extension("1.2.840.113635.100.6.2.1", false, new Uint8Array([0x05, 0x00])),
  ],
});

const leafKeys = await crypto.subtle.generateKey(P256, true, ["sign", "verify"]);
const leaf = await x509.X509CertificateGenerator.create({
  serialNumber: "03",
  subject: "CN=openpurr CONFORMANCE Signing Leaf, O=openpurr test fixtures",
  issuer: intermediate.subject,
  notBefore,
  notAfter,
  publicKey: leafKeys.publicKey,
  signingKey: intKeys.privateKey,
  signingAlgorithm: SHA384,
  extensions: [
    new x509.BasicConstraintsExtension(false, undefined, true),
    new x509.Extension("1.2.840.113635.100.6.11.1", false, new Uint8Array([0x05, 0x00])),
  ],
});

// A second, untrusted root with an otherwise identical chain, for "wrong signer" cases.
const strayRootKeys = await crypto.subtle.generateKey(P384, true, ["sign", "verify"]);
const strayRoot = await x509.X509CertificateGenerator.createSelfSigned({
  serialNumber: "11",
  name: "CN=openpurr CONFORMANCE Root CA, O=openpurr test fixtures",
  notBefore,
  notAfter,
  keys: strayRootKeys,
  signingAlgorithm: SHA384,
  extensions: [new x509.BasicConstraintsExtension(true, undefined, true)],
});
const strayInt = await x509.X509CertificateGenerator.create({
  serialNumber: "12",
  subject: "CN=openpurr CONFORMANCE Intermediate CA, O=openpurr test fixtures",
  issuer: strayRoot.subject,
  notBefore,
  notAfter,
  publicKey: intKeys.publicKey,
  signingKey: strayRootKeys.privateKey,
  signingAlgorithm: SHA384,
  extensions: [
    new x509.BasicConstraintsExtension(true, 0, true),
    new x509.Extension("1.2.840.113635.100.6.2.1", false, new Uint8Array([0x05, 0x00])),
  ],
});

const appleApiKey = await crypto.subtle.generateKey(P256, true, ["sign", "verify"]);
const googleSaKey = await crypto.subtle.generateKey(RSA, true, ["sign", "verify"]);
const pubsubKey = await crypto.subtle.generateKey(RSA, true, ["sign", "verify"]);
const pubsubJwk = await crypto.subtle.exportKey("jwk", pubsubKey.publicKey);

const fixtures = {
  comment: "GENERATED by scripts/gen-fixtures.mjs. TEST-ONLY keys; do not reuse anywhere.",
  appleRootB64: b64(root),
  appleX5c: [b64(leaf), b64(intermediate), b64(root)],
  appleLeafKeyPem: await exportPKCS8(leafKeys.privateKey),
  // Leaf and intermediate as above, but issued under an untrusted root.
  appleStrayX5c: [b64(leaf), b64(strayInt), b64(strayRoot)],
  appleApiKeyPem: await exportPKCS8(appleApiKey.privateKey),
  appleApiPublicJwk: await crypto.subtle.exportKey("jwk", appleApiKey.publicKey),
  googleServiceAccountEmail: "openpurr-test@test-project.iam.gserviceaccount.com",
  googleServiceAccountKeyPem: await exportPKCS8(googleSaKey.privateKey),
  pubsubKid: `conformance-${randomBytes(4).toString("hex")}`,
  pubsubKeyPem: await exportPKCS8(pubsubKey.privateKey),
  pubsubPublicJwk: { kty: "RSA", n: pubsubJwk.n, e: pubsubJwk.e },
  operatorSecret: randomBytes(24).toString("hex"),
};

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `${JSON.stringify(fixtures, null, 2)}\n`);
console.log(`wrote ${target}`);
