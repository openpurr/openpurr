let table: Map<string, string> | undefined;

/** The alpha-2 code for an alpha-3 code (Apple storefront), or null if unknown. */
export function alpha2FromAlpha3(alpha3: string | null | undefined): string | null {
  if (!alpha3) return null;
  if (!table) {
    table = new Map();
    for (let i = 0; i < PACKED.length; i += 5) table.set(PACKED.slice(i, i + 3), PACKED.slice(i + 3, i + 5));
  }
  return table.get(alpha3.toUpperCase()) ?? null;
}
