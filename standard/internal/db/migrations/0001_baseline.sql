-- The Standard edition's schema: Lite's D1 schema after all of its migrations (lite/migrations/
-- 0001 to 0020), on Postgres. Table and column names are the same, so a Lite export maps one to
-- one. Timestamps are epoch milliseconds in bigint columns; flags stay integer 0/1 as in D1; JSON
-- stays in text columns in the same formats. See the Lite migration named in each section for
-- what the columns mean.
--
-- Differences forced by Postgres:
--   - AUTOINCREMENT keys are identity columns (BY DEFAULT, so an import can keep the IDs).
--   - D1's COLLATE NOCASE (operator.email, the attribute search index) is an index on lower(...).
--     Queries that relied on NOCASE compare lower() on both sides.

-- 0001: every SDK request, when capture is on (spike tooling).
CREATE TABLE capture (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts            text    NOT NULL,
  method        text    NOT NULL,
  path          text    NOT NULL,
  query         text,
  platform      text,
  sdk_version   text,
  app_user_id   text,
  headers       text    NOT NULL,
  body          text,
  status        integer
);
CREATE INDEX capture_ts ON capture (ts);

-- 0002: Apple certificate chains that passed full verification.
CREATE TABLE apple_verified_chain (
  fingerprint text   PRIMARY KEY,
  leaf_spki   text   NOT NULL,
  not_before  bigint NOT NULL,
  not_after   bigint NOT NULL,
  verified_at bigint NOT NULL
);

-- 0003, 0013, 0018: customers and the app user IDs that map to them (unique per project).
CREATE TABLE customer (
  id           text    PRIMARY KEY,
  app_user_id  text    NOT NULL,
  first_seen   bigint  NOT NULL,
  project_id   text    NOT NULL DEFAULT 'default'
);
CREATE INDEX customer_project_first_seen ON customer (project_id, first_seen, id);

CREATE TABLE customer_alias (
  project_id   text    NOT NULL DEFAULT 'default',
  app_user_id  text    NOT NULL,
  customer_id  text    NOT NULL REFERENCES customer (id),
  created_at   bigint  NOT NULL,
  PRIMARY KEY (project_id, app_user_id)
);
CREATE INDEX customer_alias_customer ON customer_alias (customer_id);

-- 0003, 0005, 0014: one row per store transaction.
CREATE TABLE store_transaction (
  id                       bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  app_id                   text    NOT NULL,
  store                    text    NOT NULL,
  environment              text    NOT NULL,
  transaction_id           text    NOT NULL,
  original_transaction_id  text    NOT NULL,
  product_id               text    NOT NULL,
  base_plan_id             text,
  product_type             text    NOT NULL,
  purchased_at             bigint  NOT NULL,
  original_purchased_at    bigint  NOT NULL,
  expires_at               bigint,
  period_type              text    NOT NULL DEFAULT 'normal',
  ownership_type           text    NOT NULL DEFAULT 'PURCHASED',
  price_micros             bigint,
  currency                 text,
  storefront               text,
  revoked_at               bigint,
  revocation_reason        text,
  is_upgraded              integer NOT NULL DEFAULT 0,
  verified                 integer NOT NULL,
  source                   text    NOT NULL,
  received_at              bigint  NOT NULL,
  updated_at               bigint  NOT NULL,
  subscription_group       text,
  UNIQUE (store, transaction_id)
);
CREATE INDEX store_transaction_chain ON store_transaction (store, original_transaction_id);
CREATE INDEX store_transaction_product ON store_transaction (store, product_id);
CREATE INDEX store_transaction_updated ON store_transaction (updated_at);
CREATE INDEX store_transaction_purchased ON store_transaction (purchased_at);
CREATE INDEX store_transaction_expires ON store_transaction (expires_at) WHERE expires_at IS NOT NULL;
CREATE INDEX store_transaction_revoked ON store_transaction (revoked_at) WHERE revoked_at IS NOT NULL;

-- 0003: which customer owns a purchase chain.
CREATE TABLE purchase_owner (
  store                    text    NOT NULL,
  original_transaction_id  text    NOT NULL,
  customer_id              text    NOT NULL REFERENCES customer (id),
  app_id                   text    NOT NULL,
  updated_at               bigint  NOT NULL,
  PRIMARY KEY (store, original_transaction_id)
);
CREATE INDEX purchase_owner_customer ON purchase_owner (customer_id);

-- 0004, 0010, 0014: store-reported subscription status, and the store notifications processed.
CREATE TABLE subscription_state (
  store                     text    NOT NULL,
  original_transaction_id   text    NOT NULL,
  status                    integer,
  auto_renew                integer,
  auto_renew_product_id     text,
  expiration_intent         integer,
  unsubscribe_detected_at   bigint,
  billing_issue_detected_at bigint,
  grace_period_expires_at   bigint,
  signed_at                 bigint  NOT NULL,
  updated_at                bigint  NOT NULL,
  auto_resume_at            bigint,
  PRIMARY KEY (store, original_transaction_id)
);
CREATE INDEX subscription_state_updated ON subscription_state (updated_at);

CREATE TABLE store_notification (
  store                    text    NOT NULL,
  notification_id          text    NOT NULL,
  notification_type        text    NOT NULL,
  subtype                  text,
  environment              text    NOT NULL,
  app_id                   text,
  original_transaction_id  text,
  signed_at                bigint  NOT NULL,
  received_at              bigint  NOT NULL,
  payload                  text,
  PRIMARY KEY (store, notification_id)
);
CREATE INDEX store_notification_received ON store_notification (received_at);
CREATE INDEX store_notification_chain ON store_notification (store, original_transaction_id);

-- 0005, 0013: subscriber attributes. A cleared attribute keeps its row with value NULL.
CREATE TABLE subscriber_attribute (
  customer_id  text    NOT NULL REFERENCES customer (id),
  key          text    NOT NULL,
  value        text,
  updated_at   bigint  NOT NULL,
  received_at  bigint  NOT NULL,
  PRIMARY KEY (customer_id, key)
);
CREATE INDEX subscriber_attribute_value ON subscriber_attribute (key, lower(value));

-- 0006: outbound webhook events and their deliveries.
CREATE TABLE webhook_event (
  id           text    PRIMARY KEY,
  dedupe_key   text    NOT NULL UNIQUE,
  type         text    NOT NULL,
  app_id       text    NOT NULL,
  customer_id  text,
  environment  text    NOT NULL,
  body         text    NOT NULL,
  created_at   bigint  NOT NULL
);
CREATE INDEX webhook_event_customer ON webhook_event (customer_id, created_at);

CREATE TABLE webhook_delivery (
  event_id         text    NOT NULL REFERENCES webhook_event (id),
  endpoint         text    NOT NULL,
  status           text    NOT NULL,
  attempts         integer NOT NULL DEFAULT 0,
  next_attempt_at  bigint,
  last_status      integer,
  last_error       text,
  delivered_at     bigint,
  created_at       bigint  NOT NULL,
  PRIMARY KEY (event_id, endpoint)
);
CREATE INDEX webhook_delivery_due ON webhook_delivery (status, next_attempt_at);

-- 0007: precomputed CustomerInfo.
CREATE TABLE customer_snapshot (
  customer_id     text    PRIMARY KEY REFERENCES customer (id),
  body            text    NOT NULL,
  etag            text    NOT NULL,
  config_version  text    NOT NULL,
  updated_at      bigint  NOT NULL
);
CREATE INDEX customer_snapshot_version ON customer_snapshot (config_version);

-- 0008: daily exchange rates (units of currency per 1 USD).
CREATE TABLE fx_rate (
  date      text             NOT NULL,
  currency  text             NOT NULL,
  per_usd   double precision NOT NULL,
  source    text             NOT NULL,
  PRIMARY KEY (currency, date)
);

-- 0009, 0018: secret API keys (sk_...), stored as SHA-256 hashes.
CREATE TABLE api_key (
  id            text    PRIMARY KEY,
  key_hash      text    NOT NULL UNIQUE,
  key_prefix    text    NOT NULL,
  name          text    NOT NULL,
  scopes        text    NOT NULL,
  created_at    bigint  NOT NULL,
  last_used_at  bigint,
  expires_at    bigint,
  revoked_at    bigint,
  project_id    text    NOT NULL DEFAULT 'default'
);

-- 0010: Google Play acknowledgements to retry, and scheduled-job state.
CREATE TABLE play_ack_pending (
  purchase_token  text    PRIMARY KEY,
  app_id          text    NOT NULL,
  product_id      text    NOT NULL,
  kind            text    NOT NULL,
  attempts        integer NOT NULL DEFAULT 0,
  last_error      text,
  created_at      bigint  NOT NULL
);

CREATE TABLE job_state (
  key         text    PRIMARY KEY,
  value       text    NOT NULL,
  updated_at  bigint  NOT NULL
);

-- 0011, 0019: operators, their recovery codes, links, sessions, the audit log and settings.
CREATE TABLE operator (
  id               text    PRIMARY KEY,
  email            text    NOT NULL,
  name             text    NOT NULL,
  role             text    NOT NULL,
  app_ids          text,
  password_hash    text,
  totp_secret      text,
  totp_enabled     integer NOT NULL DEFAULT 0,
  totp_last_step   bigint,
  failed_logins    integer NOT NULL DEFAULT 0,
  locked_until     bigint,
  disabled_at      bigint,
  created_at       bigint  NOT NULL,
  last_login_at    bigint,
  locale           text
);
CREATE UNIQUE INDEX operator_email ON operator (lower(email));

CREATE TABLE recovery_code (
  operator_id  text    NOT NULL REFERENCES operator (id),
  code_hash    text    NOT NULL,
  used_at      bigint,
  PRIMARY KEY (operator_id, code_hash)
);

CREATE TABLE login_link (
  token_hash   text    PRIMARY KEY,
  operator_id  text    NOT NULL REFERENCES operator (id),
  purpose      text    NOT NULL,
  expires_at   bigint  NOT NULL,
  used_at      bigint,
  created_at   bigint  NOT NULL
);

CREATE TABLE session (
  token_hash    text    PRIMARY KEY,
  operator_id   text    NOT NULL REFERENCES operator (id),
  kind          text    NOT NULL,
  created_at    bigint  NOT NULL,
  expires_at    bigint  NOT NULL,
  last_seen_at  bigint  NOT NULL
);
CREATE INDEX session_operator ON session (operator_id);

CREATE TABLE audit_log (
  id           bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at           bigint  NOT NULL,
  operator_id  text,
  actor        text,
  token_id     text,
  source       text    NOT NULL,
  action       text    NOT NULL,
  target       text,
  details      text,
  ip           text
);
CREATE INDEX audit_log_at ON audit_log (at);

CREATE TABLE setting (
  key         text    PRIMARY KEY,
  value       text    NOT NULL,
  updated_at  bigint  NOT NULL
);

-- 0012: personal access tokens (pat_...), stored as SHA-256 hashes.
CREATE TABLE access_token (
  id            text    PRIMARY KEY,
  operator_id   text    NOT NULL REFERENCES operator (id),
  token_hash    text    NOT NULL UNIQUE,
  token_prefix  text    NOT NULL,
  name          text    NOT NULL,
  scopes        text    NOT NULL,
  created_at    bigint  NOT NULL,
  last_used_at  bigint,
  expires_at    bigint,
  revoked_at    bigint
);
CREATE INDEX access_token_operator ON access_token (operator_id);

-- 0014, 0015, 0018: daily chart totals derived from the ledger.
CREATE TABLE metric_daily (
  metric       text             NOT NULL,
  environment  text             NOT NULL,
  project_id   text             NOT NULL DEFAULT '',
  app_id       text             NOT NULL,
  store        text             NOT NULL,
  product_id   text             NOT NULL,
  date         text             NOT NULL,
  value        double precision NOT NULL,
  PRIMARY KEY (metric, environment, project_id, app_id, store, product_id, date)
);

-- 0016: promotional grants (entitlements given by an operator).
CREATE TABLE promotional_grant (
  id              text    PRIMARY KEY,
  customer_id     text    NOT NULL REFERENCES customer (id),
  entitlement_id  text    NOT NULL,
  duration        text    NOT NULL,
  starts_at       bigint  NOT NULL,
  expires_at      bigint,
  note            text,
  granted_by      text,
  source          text    NOT NULL,
  created_at      bigint  NOT NULL,
  revoked_at      bigint,
  revoked_by      text
);
CREATE INDEX promotional_grant_customer ON promotional_grant (customer_id);

-- 0017: OAuth 2.1 for MCP clients.
CREATE TABLE oauth_client (
  id             text    PRIMARY KEY,
  kind           text    NOT NULL,
  name           text    NOT NULL,
  client_uri     text,
  redirect_uris  text    NOT NULL,
  created_at     bigint  NOT NULL,
  fetched_at     bigint
);

CREATE TABLE oauth_request (
  id              text    PRIMARY KEY,
  client_id       text    NOT NULL REFERENCES oauth_client (id),
  redirect_uri    text    NOT NULL,
  state           text,
  code_challenge  text    NOT NULL,
  scope           text    NOT NULL,
  resource        text    NOT NULL,
  created_at      bigint  NOT NULL,
  expires_at      bigint  NOT NULL,
  operator_id     text,
  granted_scope   text,
  code_hash       text    UNIQUE,
  used_at         bigint,
  grant_id        text
);

CREATE TABLE oauth_grant (
  id                  text    PRIMARY KEY,
  client_id           text    NOT NULL REFERENCES oauth_client (id),
  operator_id         text    NOT NULL REFERENCES operator (id),
  scopes              text    NOT NULL,
  resource            text    NOT NULL,
  access_hash         text    UNIQUE,
  access_expires_at   bigint,
  refresh_hash        text    UNIQUE,
  refresh_expires_at  bigint,
  created_at          bigint  NOT NULL,
  last_used_at        bigint,
  revoked_at          bigint
);
CREATE INDEX oauth_grant_operator ON oauth_grant (operator_id);

-- 0018: every saved config, newest last. The current config is the row with the highest id.
CREATE TABLE config_version (
  id          bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document    text    NOT NULL,
  created_at  bigint  NOT NULL,
  created_by  text,
  note        text
);

-- 0020: price experiments and who saw which variant.
CREATE TABLE experiment (
  id          text    PRIMARY KEY,
  project_id  text    NOT NULL,
  name        text    NOT NULL,
  notes       text    NOT NULL DEFAULT '',
  variants    text    NOT NULL,
  status      text    NOT NULL,
  created_at  bigint  NOT NULL,
  created_by  text,
  started_at  bigint,
  stopped_at  bigint,
  results     text,
  results_at  bigint
);
CREATE INDEX experiment_project ON experiment (project_id, created_at);
CREATE UNIQUE INDEX experiment_running ON experiment (project_id) WHERE status = 'running';

CREATE TABLE experiment_enrollment (
  experiment_id  text    NOT NULL,
  app_user_id    text    NOT NULL,
  variant        text    NOT NULL,
  enrolled_at    bigint  NOT NULL,
  PRIMARY KEY (experiment_id, app_user_id)
);
CREATE INDEX experiment_enrollment_user ON experiment_enrollment (app_user_id);
